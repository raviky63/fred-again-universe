"""Build CHECKLIST.md: everything that still needs a human check before more data goes in.
Run after every data change:  python3 tools/verify_list.py
It reads data/*.json and lists, per file:
  - items marked "verified": false
  - support acts that come from fan reports
  - items with no date, no source, or a story that says "to verify" / "to check" / "not confirmed"
  - manual notes kept in research/open-questions.md (copied in as-is)
"""
import json, re
from pathlib import Path
from datetime import date

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
FLAG = re.compile(r"to verify|to check|still to|not confirmed|unclear|disagree", re.I)

def load(name):
    p = DATA / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else []

def label(x):
    return x.get("title") or x.get("name") or x["id"]

sections = []
counts = {}
for name in ["releases", "tracks", "events", "artists", "merch", "milestones"]:
    rows = []
    for x in load(name):
        why = []
        if x.get("verified") is False: why.append("marked unverified")
        if name in ("releases", "tracks", "events") and not x.get("date"): why.append("no date")
        if name in ("releases", "events", "merch") and not x.get("source"): why.append("no source")
        if FLAG.search(x.get("story") or ""): why.append("story says it needs checking")
        if "fan report" in (x.get("support_source") or ""): why.append("support act from a fan report: " + ", ".join(x.get("support", [])))
        if name == "artists" and x.get("photo") and not x.get("photo_credit"): why.append("photo without credit")
        if why:
            src = x.get("support_source") if "fan report" in (x.get("support_source") or "") else x.get("source", "")
            rows.append(f"- [ ] **{label(x)}** (`{x['id']}`{', ' + x['date'] if x.get('date') else ''}): {'; '.join(why)}. Source now: {src or '—'}")
    counts[name] = len(rows)
    if rows:
        sections.append(f"## {name} ({len(rows)})\n\n" + "\n".join(rows))

manual = ROOT / "research" / "open-questions.md"
extra = manual.read_text(encoding="utf-8").strip() if manual.exists() else ""

out = [f"# Checklist: what still needs checking\n",
       f"Generated by `tools/verify_list.py` on {date.today().isoformat()}. Do not edit by hand; edit the data or `research/open-questions.md` and run the script again.\n",
       "Rule: nothing new goes into data/ without a source. If a fact comes from fans (Reddit, Discord), it is marked `verified: false` until a second, independent source confirms it.\n",
       "**Totals:** " + ", ".join(f"{k} {v}" for k, v in counts.items()) + "\n"]
if extra:
    out.append("## Open questions (manual)\n\n" + extra + "\n")
out += sections
(ROOT / "CHECKLIST.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("CHECKLIST.md:", counts)
